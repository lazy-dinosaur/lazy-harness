"""Mechanical write shapes shared by public admission and deferred ledger validation.

Not a semantic judge or an acceptance grant. Legacy ledger profiles explicitly keep
fact lint deferred (proposed first), and FILE_V1 alone permits plain-string refs.
Python objects/options are server APIs; JSON fields never select a profile/authority.
"""
import copy
import hashlib
import json
from enum import Enum
from uuid import UUID, uuid4

import runner

VERSION = 'knowledge-write/v1'


class Contract(Enum):
    PUBLIC_V1 = 'public-record/v1'
    PG_LEDGER_V1 = 'pg-ledger/v1'
    FILE_LEDGER_V1 = 'file-ledger/v1'


class WriteContractError(ValueError):
    def __init__(self, errors, *, receipt_id=None, request_id=None, registration=None):
        self.errors, self.receipt_id, self.request_id = errors, receipt_id, request_id
        self.registration = copy.deepcopy(registration)
        super().__init__('; '.join(e['code'] + ': ' + e['detail'] for e in errors))

    def as_result(self):
        result = dict(ok=False, error=type(self).__name__, errors=self.errors,
                      validation_receipt_id=self.receipt_id, request_id=self.request_id)
        if self.registration is not None:
            result.update(copy.deepcopy(self.registration))
        return result


def error(code, where, detail):
    return dict(code=code, where=where, detail=detail)


def digest(value):
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True,
                                    separators=(',', ':'), allow_nan=False).encode()).hexdigest()


# These values may be generated by normalization, never by a public JSON author.
FACT_AUTHORITY = {'identity_ref', 'subject_id', 'host_id', 'assigned_area',
                  'subject_provisional', 'leaf_provisional', 'leaf_links',
                  'subject_new', 'leaf_reference_mode'}
ENVELOPE_AUTHORITY = {'actor', 'state', 'receipt_ref', 'validation_receipt_ref',
                      'trusted_identity_refs', 'contract', 'acceptance', 'request_id'}


class RecordCommand(dict):
    """Server-prepared ledger body; authority is out-of-band, not serialized.

    This is an in-process typed contract, NOT a sandbox against arbitrary Python
    execution with DB credentials. Low-level plain-dict callers use legacy admission.
    """
    def __init__(self, body, *, trusted_identity_refs=None):
        super().__init__(copy.deepcopy(body))
        self.trusted_identity_refs = copy.deepcopy(trusted_identity_refs)


def public_input(data, default_host):
    if not isinstance(data, dict):
        return None, [error('E_SCHEMA', 'record', 'record must be an object')]
    data = copy.deepcopy(data)
    errors = []
    data.pop('trusted_identity_refs', None)  # existing public JSON compatibility: ignored, never promoted
    for key in ENVELOPE_AUTHORITY & data.keys():
        errors.append(error('E_AUTHORITY', key, 'server-owned field is not public input'))
    data['host_id'] = data.get('host_id') or default_host
    for key in ('host_id', 'partition_key'):
        if not isinstance(data.get(key), str) or not data[key].strip():
            errors.append(error('E_SCHEMA', key, 'nonempty string required'))
    uid = data.get('work_unit_id')
    if uid is not None:
        try:
            data['work_unit_id'] = str(UUID(uid))
        except (ValueError, TypeError, AttributeError):
            errors.append(error('E_CONTEXT', 'work_unit_id', 'valid UUID required'))
    errors += facts_shape(data.get('facts'))
    if isinstance(data.get('facts'), list):
        for i, fact in enumerate(data['facts']):
            if isinstance(fact, dict):
                for key in FACT_AUTHORITY:
                    fact.pop(key, None)  # preserve established public ID-drop behavior
                errors += fact_shape(fact, Contract.PUBLIC_V1, prefix=f'facts.{i}.')
    return data, errors


def facts_shape(facts):
    if not isinstance(facts, list) or not facts:
        return [error('E_FACTS', 'facts', 'nonempty facts array required')]
    return [error('E_SCHEMA', f'facts.{i}', 'fact must be an object')
            for i, fact in enumerate(facts) if not isinstance(fact, dict)]


def fact_error_groups(errors, count):
    """Group only indexed fact errors; an envelope/container error stays fatal."""
    grouped = {}
    for item in errors:
        parts = item.get('where', '').split('.', 2)
        if len(parts) < 2 or parts[0] != 'facts' or not parts[1].isdigit():
            return None
        index = int(parts[1])
        if not 0 <= index < count:
            return None
        grouped.setdefault(index, []).append(item)
    return grouped

def fact_shape(fact, contract, prefix=''):
    if not isinstance(contract, Contract):
        raise TypeError('explicit Contract enum required')
    if not isinstance(fact, dict):
        return [error('E_SCHEMA', prefix.rstrip('.'), 'fact must be an object')]
    errors = []
    for key in ('fact', 'reason', 'subject', 'evidence_quote', 'kind', 'evidence_source', 'operation', 'domain', 'assigned_area', 'target_ref'):
        if key in fact and not isinstance(fact[key], str):
            errors.append(error('E_SCHEMA', prefix + key, 'string required'))
    if contract is Contract.PUBLIC_V1:
        for key in ('fact', 'reason'):
            if not isinstance(fact.get(key), str) or not fact[key].strip():
                errors.append(error('E_SCHEMA', prefix + key, 'nonempty string required'))
    parent = fact.get('parent_subject')
    if parent is not None:
        if not isinstance(parent, dict):
            errors.append(error('E_SCHEMA', prefix + 'parent_subject', 'object or null required'))
        else:
            for key in ('name', 'subject_type', 'description'):
                if key in parent and not isinstance(parent[key], str):
                    errors.append(error('E_SCHEMA', prefix + 'parent_subject.' + key, 'string required'))
    for key in ('evidence_refs', 'keywords', 'aliases'):
        if key in fact and not isinstance(fact[key], list):
            errors.append(error('E_SCHEMA', prefix + key, 'array required'))
    if isinstance(fact.get('aliases'), list) and any(not isinstance(a, str) or not a.strip() for a in fact['aliases']):
        errors.append(error('E_SCHEMA', prefix + 'aliases', 'nonempty string aliases required'))
    for i, ref in enumerate(fact.get('evidence_refs', []) if isinstance(fact.get('evidence_refs', []), list) else []):
        if contract is Contract.FILE_LEDGER_V1 and isinstance(ref, str):
            continue
        if (not isinstance(ref, dict) or ref.get('type') not in
                ('code_test', 'official_doc', 'user_utterance', 'observed_output', 'ai_inference')
                or not isinstance(ref.get('locator'), str) or not ref['locator'].strip()
                or not isinstance(ref.get('quote'), str)):
            errors.append(error('E_REF', prefix + f'evidence_refs.{i}', 'typed reference {type,locator,quote} required'))
    return errors


def admission(body, contract):
    """Envelope/storage shape only: never demand Jev/final identity before proposed."""
    if not isinstance(contract, Contract) or contract is Contract.PUBLIC_V1:
        raise TypeError('explicit ledger Contract enum required')
    if not isinstance(body, dict):
        return [error('E_SCHEMA', 'judgement', 'object required')]
    errors = []
    for key in ('host_id', 'partition_key', 'work_unit_id', 'judgement_id'):
        value = body.get(key)
        if not isinstance(value, str) or not value.strip():
            errors.append(error('E_SCHEMA', key, 'nonempty string required'))
    uid = body.get('work_unit_id')
    if isinstance(uid, str):
        if contract is Contract.PG_LEDGER_V1:
            try:
                UUID(uid)
            except ValueError:
                errors.append(error('E_CONTEXT', 'work_unit_id', 'valid UUID required'))
        elif '/' in uid or '\\' in uid or uid in ('.', '..'):
            errors.append(error('E_CONTEXT', 'work_unit_id', 'file ledger ID must be a path-free name'))
    version = body.get('version')
    if type(version) is not int or version < 1:
        errors.append(error('E_VERSION', 'version', 'positive integer required'))
    for key in ENVELOPE_AUTHORITY & body.keys():
        errors.append(error('E_AUTHORITY', key, 'server-owned envelope field'))
    if 'evidence_refs' in body:
        errors += fact_shape({'evidence_refs': body['evidence_refs']}, contract)
    errors += facts_shape(body.get('facts'))
    for i, fact in enumerate(body.get('facts', []) if isinstance(body.get('facts'), list) else []):
        errors += fact_shape(fact, contract, prefix=f'facts.{i}.')
        if not isinstance(fact, dict):
            continue
        if not isinstance(body, RecordCommand) and FACT_AUTHORITY & fact.keys():
            errors.append(error('E_AUTHORITY', f'facts.{i}', 'server-prepared RecordCommand required for authority metadata'))
        if fact.get('identity_ref') is not None:
            refs = getattr(body, 'trusted_identity_refs', None)
            if not refs or i >= len(refs) or refs[i] != fact['identity_ref']:
                errors.append(error('E_IDENTITY', f'facts.{i}.identity_ref', 'selected ref lacks server binding'))
            else:
                from identity_ref import checked, IdentityError
                try:
                    checked(refs[i], body.get('host_id'), body.get('partition_key'))
                except IdentityError as exc:
                    errors.append(error('E_IDENTITY', f'facts.{i}.identity_ref', str(exc)))
    return errors


def validate_fact(fact, contract):
    """One fact/operation shape + existing runner semantic lint; no new heuristics."""
    errors = fact_shape(fact, contract)
    if errors:
        return dict(ok=False, errors=errors, warnings=[])
    result = runner.lint_fact(fact, strict_refs=contract is not Contract.FILE_LEDGER_V1)
    errors = list(result['errors'])
    operation = fact.get('operation', 'add')
    if operation not in ('add', 'update', 'deprecate'):
        errors.append(error('E_OPERATION', 'operation', 'operation must be add|update|deprecate'))
    if operation in ('update', 'deprecate'):
        if not isinstance(fact.get('target_ref'), str) or not fact['target_ref'].strip():
            errors.append(error('E_TARGET', 'target_ref', operation + ' needs target_ref'))
        revision = fact.get('expected_revision')
        if revision is not None and (type(revision) is not int or revision < 1):
            errors.append(error('E_VERSION', 'expected_revision', 'positive integer required'))
    return dict(ok=not errors, errors=errors, warnings=result.get('warnings', []))


def validate_fixture(fixture, fact):
    if not isinstance(fixture, dict) or not isinstance(fixture.get('packet'), dict) or not isinstance(fixture.get('answers'), dict):
        return [error('E_PACKET', 'fixture', 'packet and typed answer map required')]
    packet = fixture['packet']
    if (not isinstance(packet.get('template_id'), str) or not isinstance(packet.get('template_version'), str)
            or not isinstance(packet.get('state'), dict) or not isinstance(packet.get('questions'), dict)):
        return [error('E_PACKET', 'fixture.packet', 'template identity, state and questions map required')]
    errors = runner.lint(packet)['errors']
    state = packet.get('state')
    if isinstance(state, dict):
        for key in ('candidate_fact', 'statement'):
            if key in state and state[key] != fact.get('fact'):
                errors.append(error('E_BINDING', 'packet.state.' + key, 'checked claim differs from ledger fact'))
    return errors


def failure_receipt(payload, errors, *, stage, contract, request_id=None, entry=None, checked=None, fact_index=None):
    """Exact original + checked payload digests, independent of Jev receipt semantics."""
    if not errors:
        raise ValueError('validation receipt requires typed failure reasons')
    for item in errors:
        if not all(isinstance(item.get(k), str) for k in ('code', 'where', 'detail')):
            raise ValueError('validation reasons require code/where/detail')
    body = entry['judgement_body'] if entry else (payload if isinstance(payload, dict) else {})
    version = entry.get('judgement_version', body.get('version')) if entry else body.get('version')
    return dict(receipt_id=str(uuid4()), request_id=request_id or str(uuid4()),
                contract_version=VERSION, profile=contract.value, stage=stage,
                entry_id=entry.get('entry_id') if entry else None,
                host_id=entry.get('host_id') if entry else body.get('host_id') if isinstance(body.get('host_id'), str) else None,
                work_unit_id=str(entry.get('work_unit_id')) if entry else body.get('work_unit_id') if isinstance(body.get('work_unit_id'), str) else None,
                judgement_id=entry.get('judgement_id') if entry else body.get('judgement_id') if isinstance(body.get('judgement_id'), str) else None,
                judgement_version=version if type(version) is int and version > 0 else None,
                fact_index=fact_index, payload_digest=digest(payload), checked_digest=digest(checked),
                payload=copy.deepcopy(payload), checked_payload=copy.deepcopy(checked), errors=copy.deepcopy(errors))
